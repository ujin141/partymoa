--  AFTER MOON 소개 글을 바꾼다
--
--  앞 글이 두 가지가 문제였다. 값·정원·입금 기한처럼 꼭 봐야 하는
--  줄이 소개 문장과 같은 무게로 섞여 있었고, "테이블마다 게임을 깔아
--  둡니다. 지난 파티는 50명 중 48명이 혼자 왔습니다" 가 광고 문구처럼
--  읽혔다.
--
--  이제 상세 페이지가 두 표시를 읽는다 (components/Description.tsx).
--
--    ── 소제목     줄 앞에 ── 를 붙인다
--    **굵게**      별 두 개로 감싼다
--
--  그래서 값과 정원 줄에 별을 쳤다. 크루 화면의 상세 설명 칸에서도
--  같은 표시를 쓰면 된다.
--
--  두 번 돌려도 안전하다. AFTER_MOON.sql · AFTER_MOON_PHOTOS.sql 에도
--  같은 글을 넣어 뒀으니 처음부터 다시 만들어도 같은 말이 나온다.
-- ═══════════════════════════════════════════════════════════════════

